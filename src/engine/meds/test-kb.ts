/** Build a Medication for tests. `start` and `end` are day offsets from `today` (negative = past). */
export function med(
  today: string,
  name: string,
  ingredientIds: string[],
  opts: { id?: string; start?: number; end?: number | null; reason?: string; match?: Medication["match"] } = {},
): Medication {
  const shift = (n: number): string => {
    const d = new Date(`${today}T12:00:00`);
    d.setDate(d.getDate() + n);
    return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
  };
  return {
    id: opts.id ?? `m-${name.toLowerCase().replace(/[^a-z0-9]+/g, "-")}`,
    name,
    ingredientIds,
    match: opts.match ?? (ingredientIds.length ? "exact" : "none"),
    dose: "",
    frequency: "",
    asNeeded: false,
    otc: false,
    reason: opts.reason ?? "",
    prescriber: "",
    startDate: shift(opts.start ?? -400),
    endDate: opts.end === undefined || opts.end === null ? null : shift(opts.end),
    createdAt: `${today}T12:00:00.000Z`,
    updatedAt: `${today}T12:00:00.000Z`,
  };
}
